#!/usr/bin/env python3
"""The frozen sets, checked in one place.

  manifests.py check    every file a MANIFEST lists has the recorded SHA-256
  manifests.py list     the frozen paths, one per line

A frozen set is a directory with a `MANIFEST`: lines of `<sha256>  <path>`,
the path relative to that directory (it may name another set's MANIFEST, as
the variants of a set do). Each harness checks its own MANIFEST before it
runs and refuses on a difference; this is the same comparison for all of
them, without a compiler, so that a change to a frozen file fails in seconds.
Whether a MANIFEST lists everything its set freezes is the harness's own
check (`harness.py manifest`, `gen.py --check`).

A listed file that is not in the repository is an error, except under
GENERATED: inputs a harness regenerates and compares with the MANIFEST
itself. Standard library only.
"""
import hashlib
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# MANIFEST -> path prefix of entries that are regenerated, not tracked.
# bench/bcb: `bcb.py manifest --histories DIR` writes the histories and
# compares them with these lines (the `bench bcb` job runs it).
GENERATED = {"bench/bcb/MANIFEST": "histories/"}


def manifests():
    out = subprocess.run(["git", "-C", ROOT, "ls-files", "--", "bench"], capture_output=True, text=True,
                         check=True).stdout.splitlines()
    return sorted(p for p in out if os.path.basename(p) == "MANIFEST")


def entries(manifest):
    """(sha256, repository-relative path, generated) of each line."""
    d = os.path.dirname(manifest)
    for n, line in enumerate(open(os.path.join(ROOT, manifest), encoding="utf-8"), 1):
        if not line.strip():
            continue
        parts = line.rstrip("\n").split("  ", 1)
        if len(parts) != 2 or len(parts[0]) != 64:
            raise SystemExit(f"{manifest}:{n}: not `<sha256>  <path>`")
        generated = parts[1].startswith(GENERATED.get(manifest, "\0"))
        yield parts[0], os.path.normpath(os.path.join(d, parts[1])), generated


def main():
    cmd = sys.argv[1:]
    if cmd == ["list"]:
        paths = {p for m in manifests() for _, p, g in entries(m) if not g}
        print("\n".join(sorted(paths)))
        return 0
    if cmd != ["check"]:
        raise SystemExit(__doc__)
    bad, lines, generated, files = [], 0, 0, set()
    ms = manifests()
    for m in ms:
        for digest, path, gen in entries(m):
            lines += 1
            full = os.path.join(ROOT, path)
            if not os.path.isfile(full):
                if gen:
                    generated += 1
                else:
                    bad.append(f"{m}: {path}: missing")
                continue
            files.add(path)
            with open(full, "rb") as f:
                if hashlib.sha256(f.read()).hexdigest() != digest:
                    bad.append(f"{m}: {path}: differs from the recorded hash")
    for line in bad:
        print("manifests: " + line, file=sys.stderr)
    if bad:
        return 1
    print(f"manifests ok: {len(ms)} MANIFESTs, {lines} entries, {len(files)} files match"
          + (f", {generated} regenerated by their harness" if generated else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
